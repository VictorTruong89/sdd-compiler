"""F4 §4.6 — collapsed views, rendered from the records; never edited by hand.

One renderer serves both the CLI text and the generated Markdown in `.sdd/views/`,
so the two cannot disagree (AC-4.17). A cell of the map shows how many nodes of a
family sit in a layer, and the **worst** status among them by F2 precedence:
`✗` conflict · `?` ambiguous · `~` stale · `·` unchecked · `✓` validated (F4 D5).
"""
from __future__ import annotations

from typing import Any

from ..model.layers import LAYERS
from ..model.scope import covers
from ..store.graph import shard_name
from ..store.index import GraphIndex

GENERATED_HEADER = "<!-- GENERATED by sddc — do not edit -->\n"
MARKS = {"conflict": "✗", "ambiguous": "?", "stale": "~", "unchecked": "·", "validated": "✓"}
PRECEDENCE = ("conflict", "ambiguous", "stale", "unchecked", "validated")
COLUMNS: tuple[str | None, ...] = (*LAYERS, None)                  # None: no layer
TEXT_WIDTH = 80


def family_label(family: str | None) -> str:
    if family is None:
        return "(no family)"
    return family.removeprefix("term:")


def worst(statuses: list[str]) -> str:
    return next(s for s in PRECEDENCE if s in statuses)


def map_counts(graph: Any) -> dict[str | None, dict[str | None, int]]:
    counts: dict[str | None, dict[str | None, int]] = {}
    for node in graph.nodes.values():
        row = counts.setdefault(node["family"], {})
        row[node["layer"]] = row.get(node["layer"], 0) + 1
    return counts


def map_table(graph: Any) -> str:
    """AC-4.14 — families × layers; rows by open conflicts, then by name. Counts come from
    `map_counts`, the function AC-4.18 checks against the records."""
    index = GraphIndex.build(graph)
    counts = map_counts(graph)

    def conflicts(family: str | None) -> int:
        members = set(index.by_family.get(family, []))
        return sum(1 for c in graph.conflicts.values()
                   if c["state"] == "open" and members & set(c["members"]))

    # Real families first — by open conflicts, then by name (F4 §4.6); `(global)` and
    # `(no family)` are not families, so they close the table (F4 D10).
    families = sorted(index.by_family,
                      key=lambda f: (not (f or "").startswith("term:"), -conflicts(f), family_label(f)))
    header = "| family | " + " | ".join(c or "—" for c in COLUMNS) + " |"
    lines = [header, "|" + "---|" * (len(COLUMNS) + 1)]
    for family in families:
        cells = []
        for layer in COLUMNS:
            statuses = [index.by_id[i]["status"] for i in index.by_family[family]
                        if index.by_id[i]["layer"] == layer]
            cells.append(f"{counts[family][layer]} {MARKS[worst(statuses)]}" if statuses else "")
        lines.append(f"| {family_label(family)} | " + " | ".join(cells) + " |")
    total = len(graph.nodes)
    open_conflicts = sum(1 for c in graph.conflicts.values() if c["state"] == "open")
    lines += ["", f"{total} nodes · {len([f for f in families if f and f.startswith('term:')])} families · "
                  f"{open_conflicts} open conflict{'' if open_conflicts == 1 else 's'}",
              "Marks: ✗ conflict · ? ambiguous · ~ stale · · unchecked · ✓ validated · column — no layer"]
    return "\n".join(lines) + "\n"


def family_card(graph: Any, family: str | None, links: bool = False,
                index: GraphIndex | None = None, width: int | None = TEXT_WIDTH) -> str:
    """AC-4.15 — members by layer in order L0 … L5, C, V, one line each; then what reaches the
    family from elsewhere, and how it sits among the other families. `width=None` keeps each
    claim whole: the generated Markdown has no terminal to fit (F4 D17)."""
    index = index or GraphIndex.build(graph)
    members = [index.by_id[i] for i in index.by_family.get(family, [])]
    lines = [f"## Family: {family_label(family)}", ""]
    term = graph.terms.get(family) if family else None
    if term and term.get("aliases"):
        lines += ["**Also called:** " + ", ".join(term["aliases"]), ""]
    for layer in COLUMNS:
        mine = [m for m in members if m["layer"] == layer]
        if mine:
            lines += [f"### {layer or '—'} ({len(mine)})", *(_line(n, links, width) for n in _reading_order(mine)), ""]
    scoped = _reading_order([n for n in graph.nodes.values()
                             if n["layer"] == "C" and n["family"] != family
                             and any(covers(n, m) for m in members)])
    # F4 D14: listed as lines, not bare ids — `sddc show` is deferred (B2), so an id was a dead end.
    if scoped:
        lines += [f"### In scope from elsewhere ({len(scoped)})", *(_line(n, links, width) for n in scoped), ""]
    else:
        lines.append("**In scope from elsewhere:** none")
    related = sorted({t["term"] for m in members for t in m["terms"]
                      if t["term"] != family and t["term"] in index.by_family})
    lines.append("**Related families:** " + (", ".join(family_label(r) for r in related) or "none"))
    # F4 D15: `broader` (F2 D16) is shown both ways, so a one-node family is read with its parent.
    broader = term.get("broader") if term else None
    if broader is not None and broader in index.by_family:
        lines.append(f"**Kind of:** {family_label(broader)}")
    narrower = sorted(t["id"] for t in graph.terms.values()
                      if t.get("broader") == family and t["id"] in index.by_family)
    if family and narrower:
        lines.append("**Narrower families:** " + ", ".join(
            f"{family_label(n)} ({len(index.by_family[n])})" for n in narrower))
    return "\n".join(lines) + "\n"


def _reading_order(nodes: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Source order — file, first line, id — the order a reader meets the claims in (F4 D13).
    Sorting by id put `AC-5.13` before `AC-5.2`."""
    return sorted(nodes, key=lambda n: (n["source"]["file"], n["source"]["lines"][0], n["id"]))


def _line(node: dict[str, Any], links: bool, width: int | None) -> str:
    ident = node["id"]
    if links:
        file, line = node["source"]["file"], node["source"]["lines"][0]
        ident = f"[{ident}](../../../{file}#L{line})"
    # A human view: inline emphasis and code marks are dropped from the line. The node's
    # `text` stays verbatim; a span may begin inside `**Given**` (F4 D12, R12 review).
    text = node["text"].replace("*", "").replace("`", "")
    if text.lstrip().startswith("|"):                 # a table row: cells read as one line (F4 D12)
        text = " · ".join(cell.strip() for cell in text.strip().strip("|").split("|") if cell.strip())
    text = " ".join(text.split())
    if width is not None and len(text) > width:
        text = text[:width - 1] + "…"
    # F4 D16: an ambiguous line says why, so `?` is something a reader can act on.
    why = ""
    if node["status"] == "ambiguous" and node.get("ambiguity"):
        why = " (" + ", ".join(dict.fromkeys(a["kind"] for a in node["ambiguity"])) + ")"
    return f"- {ident} {MARKS[node['status']]}{why} {text}"


def conflicts_list(graph: Any) -> str:
    """AC-4.16 — the open conflicts, interlinked records grouped and contradictions first.
    One renderer for `sddc conflicts` and `views/conflicts.md`, so the two cannot disagree."""
    from ..report import conflict_groups                # the report owns the grouping rule (F6 D9)

    index = GraphIndex.build(graph)
    groups = conflict_groups(graph)
    if not groups:
        return "No open conflicts.\n"
    lines = []
    for number, group in enumerate(groups, start=1):
        if len(groups) > 1 or len(group) > 1:
            lines.append(f"### Group {number} ({len(group)} record(s), "
                         f"{len({m for r in group for m in r['members']})} node(s))")
        for record in group:
            members = ", ".join(
                f"{m} ({index.by_id[m]['source']['file']}:{index.by_id[m]['source']['lines'][0]})"
                if m in index.by_id else f"{m} (deleted)" for m in record["members"])
            lines.append(f"- **{record['id']}** {record['kind']}: {members} — {record['rationale']}")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def stage_views(transaction: Any, store: Any, graph: Any) -> None:
    """Regenerate `.sdd/views/` in the graph's transaction (F4 §4.2); stale cards removed."""
    transaction.write_text("views/map.md", GENERATED_HEADER + "\n# Map\n\n" + map_table(graph))
    transaction.write_text("views/conflicts.md", GENERATED_HEADER + "\n# Open conflicts\n\n" + conflicts_list(graph))
    index = GraphIndex.build(graph)          # once for every card
    written = set()
    for family in index.by_family:
        name = shard_name(family).removesuffix(".jsonl") + ".md"
        written.add(name)
        transaction.write_text(f"views/families/{name}", GENERATED_HEADER + "\n" + family_card(graph, family, links=True, index=index, width=None))
    folder = store / "views" / "families"
    if folder.is_dir():
        for stale in sorted(p.name for p in folder.glob("*.md")):
            if stale not in written:
                transaction.delete(f"views/families/{stale}")
